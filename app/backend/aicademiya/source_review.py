"""Pure owner-scoped teaching/source review; no inference, search or persistence."""
import json
from fastapi import HTTPException
from .authoring import selected_tutor_materials
from .evidence import bounded_evidence_items, optional_evidence_phase, PUBLIC_CHARS, PRIVATE_CHARS, REQUEST_BYTES
from .teaching import compile_teaching, effective_profile
from .teacher_preview import saved_revision
from .version_context import material_rows
from .guided_reading import has_document_text
from .document_storage import get_document_manifest, public_document
from .reading_context import ALLOWED_QUALITY


def source_review(conn, detail, payload):
    overlay = payload.model_dump(exclude_unset=True, exclude={"question_id", "phase"})
    if any(v is None for v in overlay.values()):
        raise HTTPException(422, "Preview fields cannot be null")
    compiled_detail = {**detail, **overlay}
    compiled = compile_teaching(compiled_detail)
    qid, phase = payload.question_id, payload.phase
    saved_question = next((q for q in detail.get("questions", []) if q["id"] == qid), None)
    if qid and not saved_question:
        raise HTTPException(404, "Question not found in the saved draft")
    # Live guided worksheet turns select sources for their stored target. Optional
    # phases/generation use the saved session-wide public pool, never private files.
    question = saved_question if phase == "worksheet" else None
    public, private = selected_tutor_materials(conn, detail, qid if question else None)
    optional = optional_evidence_phase(phase)
    public_pairs = bounded_evidence_items(public, question)
    private_pairs = [] if optional else bounded_evidence_items(private, question, private=True, budget=PRIVATE_CHARS)
    included = {m["id"]: item for m, item in public_pairs + private_pairs}
    candidates = {m["id"] for m in public + private}
    selected_ids = set((question or {}).get("source_material_ids", []))
    selected_urls = set((question or {}).get("source_links", []))
    warnings = list(compiled["warnings"])
    warnings.append("Selected question/phase evidence preview only: not a complete live request, learner history, web search or proof of all-document ingestion. Only saved session material assignments and questions are used.")
    warnings.append("Evidence limits: public 32,000 characters; private 8,000 characters. Up to eight eligible files retain the first 4,000 characters each; larger pools rank overlapping 2,000-character chunks by static question words. Live guided requests have a 60,000 UTF-8-byte limit including protocol, instructions and learner context.")
    if phase != "worksheet":
        warnings.append("This phase uses the saved session-wide public evidence pool, not the selected worksheet question's assignments. Generated optional question text/keys and learner state are not generated by this review.")
    if optional:
        warnings.append("Optional quiz/reading phases exclude private selected evidence and worksheet references. Live quiz turns may separately use their own persisted formative key, not a worksheet answer key.")
    if not compiled_detail.get("learning_objectives"):
        warnings.append("No learning goals are configured.")
    if phase == "worksheet" and not saved_question:
        warnings.append("No worksheet question selected; this is the session-wide evidence pool without a current-question reference.")
    reference = None
    value = detail.get("reference_answers", {}).get(qid) if question else None
    if value and value.strip() and not optional:
        reference = {"question_id": qid, "text": value, "eligibility": compiled_detail.get("reference_policy", "after_attempt"),
                     "delivery": effective_profile(compiled_detail)["reference_delivery"]}
    elif question:
        warnings.append("No instructor reference is saved for this question.")
    if "reading" in effective_profile(compiled_detail)["phases"]:
        all_public, _ = selected_tutor_materials(conn, detail, None)
        if not bounded_evidence_items(all_public) and not has_document_text(all_public):
            warnings.append("Reading discussion is enabled without usable public evidence; live tutoring will not invent reading questions.")
    reviews = []
    for row in material_rows(conn, detail):
        raw = json.loads(row["content_json"])
        mid = row["id"]
        kind, visibility = raw.get("kind", "reference"), raw.get("visibility", "teacher")
        role = "answer_key" if kind == "answer_key" else "private_worksheet" if visibility == "teacher" and kind == "worksheet" else "private_knowledge" if visibility != "student" else "public_knowledge"
        selected = not (selected_ids or selected_urls) or mid in selected_ids or raw.get("url") in selected_urls
        item = included.get(mid)
        available_chars = len(raw.get("excerpt") or "")
        document = None
        if raw.get("document"):
            manifest, _ = get_document_manifest(conn, row)
            available_chars = sum(len(b["text"]) for p in manifest["pages"] for b in p["blocks"] if b["quality"] in ALLOWED_QUALITY)
            available_chars += sum(len(s['text'])for s in manifest.get('supplements')or[]if s['visibility']=='student')
            document = public_document(raw["document"])
        included_chars = len(item["excerpt"]) if item else 0
        if not selected:
            reason = "Not selected by the saved question's material IDs or source links."
        elif role in ("answer_key", "private_worksheet"):
            reason = "Private worksheet/answer-key bodies are never aggregated; only the current saved question reference may be used."
        elif document:
            reason = "Complete document stored. Actual page/block reads are planned from each learner request; this read-only preview does not run the model or claim these pages entered its context. Unverified regions remain excluded."
            if manifest.get('supplements'):
                reason += " Native notes and alternative text are indexed separately; staff-only supplements stay out of student AI reads until sharing is explicitly published."
            if optional and visibility != "student":
                reason = "Private complete document excluded from optional quiz/reading."
        elif raw.get("status") not in ("ready", "needs_review") or not available_chars:
            reason = "Unreadable or empty stored extraction; not usable evidence."
            warnings.append(f"Material {mid}: no usable stored extraction.")
        elif optional and visibility != "student":
            reason = "Private evidence is excluded from optional quiz/reading phases."
        elif item:
            reason = "Included using the live bounded evidence selector."
            if included_chars < available_chars:
                reason += " Only a bounded snippet is included, not the complete extracted document."
                warnings.append(f"Material {mid}: bounded snippet includes {included_chars} of {available_chars} available characters.")
        elif mid in candidates:
            reason = "Excluded after ranking because the evidence character budget is exhausted."
            warnings.append(f"Material {mid}: evidence character budget exhausted.")
        else:
            reason = "Not eligible for live evidence."
        reviews.append({"id": mid, "title": raw.get("title", ""), "kind": kind, "visibility": visibility,
                        "status": raw.get("status", "unknown"), "role": role, "selected": selected, "included": bool(item),
                        "available_chars": available_chars, "included_chars": included_chars, "reason": reason,
                        "warning": raw.get("warning"), "extraction_report": raw.get("extraction_report"),
                        **({"document": document} if document else {})})
    if any(x.get("document") for x in reviews):
        warnings.append("Full documents use a separate bounded per-turn read planner across all saved pages. The first-4,000/50,000-character preview limits above describe legacy excerpt-only materials, not full document storage. This screen is not a live document-read plan.")
    # This is a definite lower bound, not an invented complete live request size.
    static_bytes = len(json.dumps({"compiled_teaching": compiled["text"], "public_evidence": [v for _, v in public_pairs],
                                  "private_evidence": [v for _, v in private_pairs], "private_reference": reference}, ensure_ascii=False).encode("utf-8"))
    if static_bytes > REQUEST_BYTES:
        warnings.append("Compiled instructions and selected evidence alone exceed the live 60,000-byte request budget; a live guided request will reject this context rather than silently truncate instructions.")
    return {"scope": "unsaved_instruction_overlay" if overlay else "saved_draft", "saved_revision": saved_revision(conn, detail),
            "question_id": qid, "phase": phase, "compiled": compiled,
            "public_evidence": [{"material_id": m["id"], **v} for m, v in public_pairs],
            "private_evidence": [{"material_id": m["id"], **v} for m, v in private_pairs],
            "private_reference": reference, "materials": reviews, "warnings": list(dict.fromkeys(warnings)),
            "budgets": {"public_chars": PUBLIC_CHARS, "private_chars": PRIVATE_CHARS, "request_bytes": REQUEST_BYTES}}
