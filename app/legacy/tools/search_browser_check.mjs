// Real UI/backend/SQLite/Tavily; model decisions are explicitly a protocol fixture.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {chromium,expect}=require('@playwright/test');
const base=process.env.AICADEMIYA_TEST_URL;
if(!base)throw new Error('An isolated search QA server URL is required');
const out=path.resolve(import.meta.dirname,'../artifacts/web-search');
await fs.mkdir(out,{recursive:true});
if(process.env.TMPDIR){process.env.TEMP=process.env.TMPDIR;process.env.TMP=process.env.TMPDIR;}
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const checks=[],screenshots=[],errors=[],chatFlags=[];
const shot=async(name,page)=>{const file=path.join(out,name+'.png');await page.screenshot({path:file,fullPage:true});screenshots.push(file);};
const observe=page=>{page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(new URL(r.url()).pathname.endsWith('/chat'))chatFlags.push(r.postDataJSON().web_search);});};
const sendAsk=async(page,text)=>{
 const count=await page.locator('.message-assistant').count();
 await page.getByRole('button',{name:'Ask a follow-up',exact:true}).click();
 await page.getByRole('textbox',{name:'Ask a follow-up',exact:true}).fill(text);
 await page.getByRole('button',{name:'Send',exact:true}).click();
 await expect(page.locator('.message-assistant')).toHaveCount(count+1,{timeout:60000});
};
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();observe(page);
 await page.goto(base);
 await page.getByRole('button',{name:'Student 2',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Language Testing & Assessment',exact:true})).toBeVisible();
 await page.goto(base+'/#/workspace/session-4');
 await expect(page.locator('#question-select')).toBeVisible();
 const toggle=page.getByRole('switch',{name:'Web search',exact:true});
 await expect(toggle).not.toBeChecked();await expect(toggle).toBeEnabled();
 await sendAsk(page,'Explain the concept without searching. [Synthetic offline request]');
 await expect(page.locator('.message-assistant').last()).toContainText('Protocol fixture — offline');
 await expect(page.locator('.message-assistant').last().locator('.web-source-link')).toHaveCount(0);
 checks.push('Student switch defaults off and skips search');
 await toggle.click();await expect(toggle).toBeChecked();
 await page.reload();await expect(toggle).toBeChecked();
 checks.push('Student switch choice survives reload');
 await sendAsk(page,'Find public Cambridge English evidence about assessment validity and reliability. [Synthetic integration request]');
 await expect(page.locator('.message-assistant').last()).toContainText('Inline citations deliberately omitted');
 const link=page.locator('.message-assistant').last().locator('.web-source-link').first();
 await expect(link).toContainText('[W1]');
 await expect(link).toHaveAttribute('href',/^https:\/\//);
 const href=await link.getAttribute('href');
 await expect(link).toHaveAttribute('target','_blank');
 const response=await page.request.get(base+'/api/sessions/session-4/workspace');
 const saved=await response.json();
 if(saved.messages.at(-1).citations[0].url!==href)throw new Error('Source chip is not the persisted provider result');
 await expect(page.locator('.message-assistant').last().locator('.web-source-link')).toHaveCount(saved.messages.at(-1).citations.length);
 if(Object.keys(saved.attempts).length)throw new Error('Searching/follow-up changed the saved answer');
 checks.push('Student switch on forces real Tavily and every source remains linked despite omitted model citations');
 await link.click({trial:true});
 await shot('web-source-desktop',page);
 await page.reload();await expect(page.locator('.web-source-link').first()).toContainText('[W1]');
 checks.push('Source label and snippet survive workspace reload');
 await toggle.click();await expect(toggle).not.toBeChecked();
 await sendAsk(page,'Continue offline after switching search off. [Synthetic request]');
 await expect(page.locator('.message-assistant').last()).toContainText('Protocol fixture — offline');
 await expect(page.locator('.message-assistant').last().locator('.web-source-link')).toHaveCount(0);
 checks.push('Switching off again bypasses search and does not reuse old sources');
 await expect(page.locator('.locale-button')).toHaveCount(0);
 await expect(page.getByRole('switch',{name:'Web search',exact:true})).not.toBeChecked();
 await expect(page.locator('.web-source-link').first()).toHaveAttribute('href',href);
 await page.setViewportSize({width:390,height:844});
 await page.locator('.web-source-link').first().click({trial:true});
 await expect(page.locator('.web-source-link').first()).toBeInViewport();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1))throw new Error('Search source causes mobile page overflow');
 await shot('web-source-mobile-en',page);
 checks.push('English search switch, direct source links and 390px layout work');
 const teacher=await browser.newContext({viewport:{width:1440,height:1000}});
 await teacher.request.post(base+'/api/auth/demo',{data:{role:'teacher'}});
 const preview=await teacher.newPage();observe(preview);
 await preview.goto(base+'/#/workspace/session-4');
 const teacherToggle=preview.getByRole('switch',{name:'Web search',exact:true});
 await expect(teacherToggle).not.toBeChecked();await teacherToggle.click();await expect(teacherToggle).toBeChecked();
 await sendAsk(preview,'Find public assessment sources for this teacher preview. [Synthetic teacher request]');
 await expect(preview.locator('.web-source-link').first()).toContainText('[W1]');
 const teacherWork=await (await preview.request.get(base+'/api/sessions/session-4/workspace')).json();
 if(teacherWork.user.role!=='teacher'||teacherWork.messages.length!==2)throw new Error('Teacher preview was not isolated');
 await expect(preview.locator('.web-source-link')).toHaveCount(teacherWork.messages.at(-1).citations.length);
 await shot('teacher-search-switch',preview);
 checks.push('Teacher preview has an independent working search switch and mandatory source links');
 const administrator=await browser.newContext();
 await administrator.request.post(base+'/api/auth/demo',{data:{role:'admin'}});
 const settings=await administrator.newPage();observe(settings);
 await settings.goto(base+'/#/settings');
 await expect(settings.getByRole('heading',{name:'Web search · Tavily',exact:true})).toBeVisible();
 await expect(settings.getByText('Configured · available in live mode',{exact:true})).toBeVisible();
 await shot('web-search-settings',settings);
 checks.push('Administrator sees search configuration status without API key');
 if(errors.length)throw new Error(JSON.stringify(errors));
 expect(chatFlags).toEqual([false,true,false,true]);
 const result={status:'passed',checks,screenshots,page_errors:errors,real_backend:true,real_search:true,real_model:false,source_url:href,chat_search_flags:chatFlags};
 await fs.writeFile(path.join(out,'browser-result.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify({status:result.status,checks:checks.length,screenshots:screenshots.length,real_search:true,real_model:false}));
}finally{await browser.close();}
